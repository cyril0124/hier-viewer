import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, writeFile, rm } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { promisify } from 'node:util';
import { preview } from 'vite';
import { chromium } from 'playwright';

const execute = promisify(execFile);
const binary = resolve(process.argv[2] ?? 'target/debug/hier-viewer');
await mkdir('target', { recursive: true });
const workspace = await mkdtemp(resolve('target/coverage-legend-'));
let server;
let browser;
try {
  const report = join(workspace, 'report');
  const output = join(workspace, 'viewer');
  await mkdir(report);
  const rtl = join(workspace, 'design.sv');
  await writeFile(rtl, 'module Child(input wire x, output wire y); assign y=x; endmodule\nmodule Top; Child a(); Child b(); Child c(); Child d(); Child e(); endmodule\n');
  const scores = [0, 50, 80, 95, null];
  const scopes = scores.map((value, index) => `<scope type="instance" name="${'abcde'[index]}">${value === null ? '' : `<metric name="Line" value="${value}/100" excl="0"/><metric name="Cond" value="${100 - value}/100" excl="0"/>`}</scope>`).join('');
  const xml = `<session version="1.1" release="test"><old_coverage><scope type="instance" name="tb"><scope type="instance" name="dut"><metric name="Line" value="10/100" excl="0"/><metric name="Cond" value="90/100" excl="0"/>${scopes}</scope></scope></old_coverage></session>`;
  await writeFile(join(report, 'session.xml'), xml);
  await execute(binary, [rtl, '--no-wizard', '--output', output, '--coverage-report', report, '--', '--top', 'Top'], { timeout: 60000 });
  server = await preview({ configFile: false, root: workspace, build: { outDir: output }, preview: { host: '127.0.0.1', port: 0, open: false } });
  browser = await chromium.launch({ headless: true });
  for (const width of [1440, 390]) {
    const page = await browser.newPage({ viewport: { width, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(server.resolvedUrls.local[0]);
    await page.waitForFunction(() => !document.querySelector('#coverage-metric-select').disabled);
    const paths = () => page.locator('.match-path').allTextContents();
    const bucket = (index, chart = false) => page.locator(`${chart ? '.chart-coverage-key' : '#coverage-legend'} [data-coverage-bucket="${index}"]`);
    const clear = (chart = false) => page.locator(`${chart ? '.chart-coverage-key' : '#coverage-legend'} [data-coverage-filter-clear]`);
    const canvasBefore = await page.locator('#treemap').screenshot();
    await bucket(0).click();
    await page.locator('#toggle-match-btn').click();
    assert.deepEqual(await paths(), ['Top', 'a']);
    assert.notDeepEqual(await page.locator('#treemap').screenshot(), canvasBefore);
    assert.equal(await bucket(0).getAttribute('aria-pressed'), 'true');
    await bucket(3).click();
    assert.deepEqual(await paths(), ['Top', 'a', 'd']);
    await page.locator('#filter-scope-select').selectOption('path');
    await page.locator('#search-input').fill('d');
    await page.waitForFunction(() => document.querySelectorAll('.match-path').length === 1);
    assert.deepEqual(await paths(), ['d']);
    await page.locator('#search-input').fill('');
    await clear().click();
    await bucket(4).click();
    assert.deepEqual(await paths(), ['e'], 'Hidden synthetic root is not a No data match');

    await page.locator('#close-match-btn').click();
    await page.locator('#view-pie-btn').click();
    await page.locator('#chart-level-select').selectOption('1');
    await page.waitForFunction(() => document.querySelectorAll('.chart-slice').length === 1);
    assert.equal(await bucket(4, true).getAttribute('aria-pressed'), 'true');
    await clear(true).click();
    await page.waitForFunction(() => document.querySelectorAll('.chart-slice').length === 5);
    await bucket(0, true).click();
    await page.waitForFunction(() => document.querySelectorAll('.chart-slice').length === 1);
    assert.deepEqual(await page.locator('.chart-legend-label').allTextContents(), ['a']);
    await page.locator('#coverage-metric-select').selectOption('branch');
    await page.waitForFunction(() => !!document.querySelector('.chart-empty'));
    assert.equal(await clear(true).isEnabled(), true, 'Empty charts keep filter recovery controls');
    await clear(true).click();
    await page.waitForFunction(() => document.querySelectorAll('.chart-slice').length === 5);
    await page.locator('#coverage-metric-select').selectOption('line');
    await bucket(3, true).click();
    await page.locator('#view-three-btn').click();
    await page.waitForFunction(() => document.querySelector('#chart-status').textContent.includes('3D ready'));
    assert.deepEqual(await page.locator('.chart-legend-label').allTextContents(), ['d']);
    await page.locator('#coverage-metric-select').selectOption('condition');
    await page.waitForFunction(() => document.querySelector('.chart-legend-label')?.textContent === 'a');
    await clear(true).click();
    await bucket(4, true).click();
    await page.waitForFunction(() => document.querySelector('.chart-legend-label')?.textContent === 'e');
    await page.locator('#coverage-metric-select').selectOption('off');
    await page.waitForFunction(() => document.querySelectorAll('.chart-legend-item').length === 5);
    await page.locator('#coverage-metric-select').selectOption('line');
    await page.waitForFunction(() => !!document.querySelector('.chart-coverage-key'));
    assert.equal(await bucket(4, true).getAttribute('aria-pressed'), 'false');
    await bucket(0, true).click();
    await page.locator('#coverage-clear-btn').click();
    await page.waitForFunction(() => document.querySelectorAll('.chart-legend-item').length === 5);
    assert.equal(await page.locator('[data-coverage-bucket][aria-pressed="true"]').count(), 0);
    assert.deepEqual(errors, []);
    console.log(`${width}: coverage range multiselect, text intersection, No data, treemap pixels, 2D/3D filtering and reset passed`);
    await page.close();
  }
} finally {
  await browser?.close();
  await server?.close();
  await rm(workspace, { recursive: true, force: true });
}
